"""scorecard: measure the guard against tests/fixtures/ and track known gaps.

Every tests/fixtures/*.txt is a case: files named benign-* must come back clean,
every other file must be flagged. Known failures are recorded in
tests/known_gaps.json so CI can be green while the gaps stay visible:
CI fails on any *new* failure (a regression, or a new fixture that fails
without being recorded).

    python3 scorecard.py            # print the scorecard
    python3 scorecard.py --update   # rewrite tests/known_gaps.json and DETECTION.md
"""

from __future__ import annotations

import collections
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT))
from data_not_instructions import guard  # noqa: E402

FIXTURES = ROOT / "tests" / "fixtures"
GAPS = ROOT / "tests" / "known_gaps.json"
REPORT = ROOT / "DETECTION.md"


def evaluate() -> dict:
    results = {}
    for f in sorted(FIXTURES.glob("*.txt")):
        name = f.stem
        benign = name.startswith("benign-")
        doc = guard(f.read_text(encoding="utf-8", errors="replace"), source=f.name)
        results[name] = {"benign": benign, "ok": doc.suspicious != benign, "warnings": doc.warnings}
    return results


def gaps_of(results: dict) -> dict:
    return {
        "missed_attacks": sorted(n for n, r in results.items() if not r["ok"] and not r["benign"]),
        "false_alarms": sorted(n for n, r in results.items() if not r["ok"] and r["benign"]),
    }


def by_set(results: dict) -> dict:
    sets = collections.defaultdict(lambda: [0, 0])
    for name, r in results.items():
        s = sets[name.split("-")[0]]
        s[0] += r["ok"]
        s[1] += 1
    return dict(sorted(sets.items()))


def render(results: dict) -> str:
    ok = sum(r["ok"] for r in results.values())
    attacks = [r for r in results.values() if not r["benign"]]
    benign = [r for r in results.values() if r["benign"]]
    gaps = gaps_of(results)
    lines = [
        "# Detection scorecard",
        "",
        "Generated by `python3 scorecard.py --update` from every file in `tests/fixtures/`.",
        "Files named `benign-*` must come back clean; every other file is an attack that must be flagged.",
        "",
        "**What this measures:** only the *warning* layer (phrase and markup detection).",
        "Every document, flagged or not, is still fenced in nonce-tagged tags with the",
        "data-not-instructions system rule; that protection does not depend on language or wording.",
        "",
        f"| | Result |",
        f"|---|---|",
        f"| All fixtures | {ok}/{len(results)} as expected |",
        f"| Attacks flagged | {sum(r['ok'] for r in attacks)}/{len(attacks)} |",
        f"| Harmless files clean | {sum(r['ok'] for r in benign)}/{len(benign)} |",
        "",
        "## By set",
        "",
        "| Set | As expected | Rate |",
        "|---|---|---|",
    ]
    for s, (g, t) in by_set(results).items():
        lines.append(f"| `{s}-*` | {g}/{t} | {100 * g // t}% |")
    lines += [
        "",
        "## Known gaps",
        "",
        "Recorded in [`tests/known_gaps.json`](tests/known_gaps.json). CI fails if any other fixture fails.",
        "",
        f"**False alarms ({len(gaps['false_alarms'])}):** " + (", ".join(f"`{n}`" for n in gaps["false_alarms"]) or "none"),
        "",
        f"**Missed attacks ({len(gaps['missed_attacks'])}):** " + (", ".join(f"`{n}`" for n in gaps["missed_attacks"]) or "none"),
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    results = evaluate()
    if "--update" in argv:
        GAPS.write_text(json.dumps(gaps_of(results), indent=1) + "\n", encoding="utf-8")
        REPORT.write_text(render(results), encoding="utf-8")
        print(f"wrote {GAPS.relative_to(ROOT)} and {REPORT.relative_to(ROOT)}")
    ok = sum(r["ok"] for r in results.values())
    print(f"{ok}/{len(results)} fixtures as expected")
    for s, (g, t) in by_set(results).items():
        print(f"  {s:10} {g:3}/{t:<3} {100 * g // t:3d}%")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
